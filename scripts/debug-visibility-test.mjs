import assert from 'node:assert/strict';
import { createDebugVisibility } from '../plugins/editor/debug-visibility.mjs';
const visibility = createDebugVisibility(true);
assert.equal(visibility.expanded(), false);
visibility.updateStop('python:session:1');
assert.equal(visibility.expanded(), true, 'A new stop temporarily reveals a collapsed debugger');
assert.equal(visibility.preference(), true, 'A stop must not overwrite the saved preference');
assert.equal(visibility.toggle(), true);
visibility.updateStop('python:session:1');
assert.equal(visibility.expanded(), false, 'Repeated updates cannot reopen a manually dismissed stop');
visibility.updateStop('python:session:2');
assert.equal(visibility.expanded(), true, 'The next step/breakpoint reveals again');
visibility.updateStop('');
assert.equal(visibility.expanded(), false, 'Continue restores the preference');
visibility.updatePreference(false);
assert.equal(visibility.expanded(), true);
visibility.updateStop('javascript:session:1');
assert.equal(visibility.toggle(), true);
visibility.updateStop('');
assert.equal(visibility.expanded(), false);
console.log('PASS: persistent preference, transient stops, dismiss deduplication, continue, and multiple debugger IDs');
