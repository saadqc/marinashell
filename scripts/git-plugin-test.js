const fs = require('fs'); const path = require('path'); const os = require('os'); const assert = require('assert/strict');
const { execFileSync } = require('child_process');
const { createHostCommands } = require('../main/services/hostCommands');
const { createGitService, parseStats } = require('../plugins/git/service');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'marina-git-'));
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
async function test() {
  git('init', '-b', 'main'); git('config', 'user.name', 'Fixture'); git('config', 'user.email', 'fixture@example.invalid');
  fs.writeFileSync(path.join(root, 'file.js'), 'const answer = 1;\n'); git('add', '.'); git('commit', '-m', 'initial');
  const service = createGitService(createHostCommands(null));
  require('../plugins/git/operations').installGitOperations(service);
  const { repository } = await service.discover({ cwd: root, host: '__local__' }); assert(repository);
  assert.equal((await service.snapshot(repository.id)).files.length, 0);
  fs.writeFileSync(path.join(root, 'file.js'), 'const answer = 2;\n'); git('add', 'file.js');
  fs.appendFileSync(path.join(root, 'file.js'), 'console.log(answer);\n');
  const unusual = '- odd\n雪 $(false).js'; fs.writeFileSync(path.join(root, unusual), 'hello\n');
  let s = await service.snapshot(repository.id);
  assert.equal(s.files.length, 3); assert(s.files.some(f => f.scope === 'staged')); assert(s.files.some(f => f.scope === 'unstaged'));
  const untracked = s.files.find(f => f.path === unusual); assert.equal(untracked.added, 1);
  assert.equal((await service.content(s.id, untracked.id)).newText, 'hello\n');
  const staged = s.files.find(f => f.scope === 'staged'); const content = await service.content(s.id, staged.id);
  assert.match(content.oldText, /answer = 1/); assert.match(content.newText, /answer = 2/); assert(!content.newText.includes('console.log'));
  fs.writeFileSync(path.join(root, unusual), 'other\n'); await assert.rejects(service.content(s.id, untracked.id), /changed/);
  await assert.rejects(service.operation(s.id, 'stage', { all: true }), /changed/);
  s = await service.snapshot(repository.id); await service.operation(s.id, 'stage', { all: true });
  s = await service.snapshot(repository.id); assert(s.files.every(f => f.scope === 'staged'));
  await service.operation(s.id, 'unstage', { fileIds: [s.files.find(f => f.path === unusual).id] });
  assert.equal(git('ls-files', '--', unusual), '');
  git('add', '.'); git('commit', '-m', 'changes'); git('switch', '-c', 'feature');
  git('mv', 'file.js', 'renamed.js'); git('commit', '-m', 'rename');
  s = await service.snapshot(repository.id, 'main'); assert.equal(s.files.length, 1); assert.equal(s.files[0].status, 'R100');
  const renamed = await service.content(s.id, s.files[0].id); assert.equal(renamed.oldText, renamed.newText);
  assert.equal(git('branch', '--show-current').trim(), 'feature', 'Comparing does not switch branches');
  fs.writeFileSync(path.join(root, 'binary.dat'), Buffer.from([0, 1, 2])); s = await service.snapshot(repository.id);
  assert.match((await service.content(s.id, s.files.find(f => f.path === 'binary.dat').id)).unavailable, /Binary/);
  fs.symlinkSync('missing-target', path.join(root, 'broken-link')); s = await service.snapshot(repository.id);
  assert.equal((await service.content(s.id, s.files.find(f => f.path === 'broken-link').id)).newText, 'missing-target');
  fs.writeFileSync(path.join(root, 'large.txt'), Buffer.alloc(9 * 1024 * 1024, 97)); git('add', '--', 'large.txt');
  s = await service.snapshot(repository.id);
  assert.match((await service.content(s.id, s.files.find(f => f.path === 'large.txt').id)).unavailable, /2 MB/);
  assert.deepEqual([...parseStats('1\t2\t\0old\0new\0').values()], [{ added: 1, deleted: 2 }]);
  assert.equal((await service.discover({ cwd: os.tmpdir() })).repository, null);
  s = await service.snapshot(repository.id); await service.operation(s.id, 'createBranch', { branch: 'new-branch' });
  assert.equal(git('branch', '--show-current').trim(), 'new-branch');
  s = await service.snapshot(repository.id); await service.operation(s.id, 'switchBranch', { branch: 'feature' });
  const bare = path.join(root, 'remote.git'); git('init', '--bare', bare); git('remote', 'add', 'origin', bare);
  s = await service.snapshot(repository.id); await service.operation(s.id, 'push', { remote: 'origin', branch: 'feature' });
  s = await service.snapshot(repository.id); await service.operation(s.id, 'fetch', { remote: 'origin' });
  console.log('PASS: real Git staged/unstaged/untracked, counts, hostile filenames, stale snapshots, rename/branch comparison, binary files and non-repository discovery');
}
test().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => fs.rmSync(root, { recursive: true, force: true }));
